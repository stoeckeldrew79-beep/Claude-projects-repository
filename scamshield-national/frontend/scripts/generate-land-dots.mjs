// Generates launch/landDots.js: which cells of a world grid are land, for the
// dotted world map on the launch page. Computed once from world-atlas and
// committed, so the page ships ~1KB of bits instead of a map dataset.
// Re-run with `node scripts/generate-land-dots.mjs`.
import fs from 'fs';
import { createRequire } from 'module';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const land = feature(require('world-atlas/land-110m.json'), require('world-atlas/land-110m.json').objects.land);

const COLS = 180;
const ROWS = 76; // 84°N to 68°S — Antarctica left off, it reads as noise
const bits = [];
for (let r = 0; r < ROWS; r++) {
  const lat = 84 - (r + 0.5) * (152 / ROWS);
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + (c + 0.5) * (360 / COLS);
    bits.push(geoContains(land, [lon, lat]) ? 1 : 0);
  }
}
let hex = '';
for (let i = 0; i < bits.length; i += 4) hex += ((bits[i] << 3) | (bits[i + 1] << 2) | (bits[i + 2] << 1) | (bits[i + 3] | 0)).toString(16);
fs.writeFileSync(
  new URL('../launch/landDots.js', import.meta.url),
  `// GENERATED by scripts/generate-land-dots.mjs — do not edit by hand.\n` +
    `// A ${COLS}x${ROWS} land mask (84°N–68°S, equirectangular), 4 cells per hex digit.\n` +
    `export const LAND_COLS = ${COLS};\nexport const LAND_ROWS = ${ROWS};\nexport const LAND_HEX =\n  '${hex}';\n`
);
console.log('land cells', bits.filter(Boolean).length, 'of', bits.length, 'hex chars', hex.length);
