// Generates src/utils/countryData.ts from the world-countries dataset.
//
// The table used to be hand-written. It fell behind twice: 13 entries while
// the database held 110 countries, then 110 while the database held 125 —
// the second gap opened within hours, because the content routines add
// countries on their own and a hand-kept list cannot win that race.
//
// Generated once and committed, so there is no runtime dependency and no
// dataset shipped to the browser. Re-run with `npm run generate-countries`
// if the upstream data is ever updated.
const fs = require('fs');
const path = require('path');
const countries = require('world-countries');

const rows = countries
  .filter((c) => c.cca2 && Array.isArray(c.latlng) && c.latlng.length === 2)
  .sort((a, b) => a.cca2.localeCompare(b.cca2))
  .map((c) => {
    const name = c.name.common.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    const [lat, lon] = c.latlng;
    return `  ${c.cca2}: { name: '${name}', lat: ${lat}, lon: ${lon} },`;
  });

const out = `// GENERATED by scripts/generate-countries.cjs — do not edit by hand.
// Run \`npm run generate-countries\` to rebuild from the world-countries dataset.
//
// Every ISO 3166-1 alpha-2 country, with the centroid used to place its marker
// on the globe. Complete on purpose: a country missing from here cannot be
// drawn at all, and the hand-kept version this replaces was silently hiding
// 97 of 110 countries, then 15 more within hours of being brought up to date.
export interface CountryInfo {
  name: string;
  lat: number;
  lon: number;
}

export const COUNTRIES: Record<string, CountryInfo> = {
${rows.join('\n')}
};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'utils', 'countryData.ts'), out);
console.log(`generate-countries: wrote ${rows.length} countries`);
